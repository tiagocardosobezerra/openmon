  const wanted = params.get('lang') || navigator.language || 'en';
  const lang = /^pt/i.test(wanted) ? 'pt-BR' : 'en';

  function t(key, vars = {}) {
    const raw = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.en[key] ?? key;
    if (Array.isArray(raw)) return raw;
    return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : String(vars[k])));
  }

  // Agent details arrive in English from the daemon; translate the known ones.
  // What the agent is doing or asking, in everyday words. The hooks report
  // tool names ("Allow Bash: npm publish?", "Edit app.js"); people who do
  // not know the tools read "wants to run a command: npm publish".
  const TOOL_WORDS = {
    en: {
      run: ['Running', 'run a command'], edit: ['Editing', 'edit'], write: ['Creating', 'create'], read: ['Reading', 'read'],
      search: ['Searching', 'search for'], web: ['Opening', 'open the page'], websearch: ['Searching the web for', 'search the web for'],
      agent: ['Starting a helper', 'start a helper agent'], todo: ['Planning', 'update its plan'], tool: ['Using', 'use'],
      allow: 'Wants permission to {what}', file: 'the file {x}',
    },
    'pt-BR': {
      run: ['Rodando', 'rodar um comando'], edit: ['Editando', 'editar'], write: ['Criando', 'criar'], read: ['Lendo', 'ler'],
      search: ['Buscando', 'buscar'], web: ['Abrindo', 'abrir a página'], websearch: ['Buscando na web', 'buscar na web'],
      agent: ['Chamando um ajudante', 'chamar um agente ajudante'], todo: ['Planejando', 'atualizar o plano'], tool: ['Usando', 'usar'],
      allow: 'Quer permissão para {what}', file: 'o arquivo {x}',
    },
  };
  const KIND = {
    Bash: 'run', PowerShell: 'run', BashOutput: 'run', Edit: 'edit', MultiEdit: 'edit', NotebookEdit: 'edit', Write: 'write',
    Read: 'read', Grep: 'search', Glob: 'search', LS: 'read', WebFetch: 'web', WebSearch: 'websearch', Task: 'agent', Agent: 'agent', TodoWrite: 'todo',
  };

  function plain(tool, rest, asking) {
    const words = TOOL_WORDS[lang] || TOOL_WORDS.en;
    let kind = KIND[tool];
    let target = rest;
    if (!kind && /^mcp__/.test(tool)) {
      const [, server, name] = tool.split('__');
      kind = 'tool';
      target = `${(name || '').replace(/_/g, ' ')} (${server})${rest ? ` ${rest}` : ''}`;
    }
    if (!kind) return null;
    const isFile = ['edit', 'write', 'read'].includes(kind) && target;
    const what = isFile ? words.file.replace('{x}', target) : target;
    if (asking) return words.allow.replace('{what}', `${words[kind][1]}${what ? (kind === 'run' || kind === 'agent' ? ': ' : ' ') + what : ''}`);
    return `${words[kind][0]}${what ? (kind === 'run' || kind === 'agent' ? ': ' : ' ') + what : ''}`;
  }

  function detail(text) {
    if (!text) return '';
    const allow = /^Allow (.*)\?$/s.exec(text);
    const body = allow ? allow[1] : text;
    const m = /^([A-Za-z][\w-]*?)(?:: | )(.*)$/s.exec(body) || /^([A-Za-z][\w-]*)$/.exec(body);
    if (m) {
      const said = plain(m[1], m[2] || '', Boolean(allow));
      if (said) return said;
    }
    if (lang === 'en') return text;
    if (allow) return t('detail.allow', { what: allow[1] });
    const key = `detail.${text}`;
    return STRINGS[lang][key] || text;
  }

  window.OpenmonI18n = { lang, t, detail };
