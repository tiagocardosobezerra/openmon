  const wanted = params.get('lang') || navigator.language || 'en';
  const lang = /^pt/i.test(wanted) ? 'pt-BR' : 'en';

  function t(key, vars = {}) {
    const raw = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.en[key] ?? key;
    if (Array.isArray(raw)) return raw;
    return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : String(vars[k])));
  }

  // Agent details arrive in English from the daemon; translate the known ones.
  function detail(text) {
    if (!text || lang === 'en') return text || '';
    const allow = /^Allow (.*)\?$/s.exec(text);
    if (allow) return t('detail.allow', { what: allow[1] });
    const key = `detail.${text}`;
    return STRINGS[lang][key] || text;
  }

